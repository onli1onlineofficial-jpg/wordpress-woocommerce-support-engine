#!/bin/bash

###############################################################################
# WordPress Health Check Utility
#
# Description:
# Performs a comprehensive health check of a WordPress installation.
#
# Checks:
# - WordPress Installation
# - WordPress Version
# - PHP Version
# - MySQL Version
# - Active Theme
# - Active Plugins
# - Database Status
# - Cache
# - Debug Mode
# - Disk Space
#
# Requirements:
# - Bash
# - WP-CLI
#
# Usage:
# chmod +x health-check.sh
# ./health-check.sh
###############################################################################

set -e

echo "======================================================="
echo "         WordPress Health Check Utility"
echo "======================================================="
echo ""

###############################################################################
# Verify WordPress
###############################################################################

if ! wp core is-installed >/dev/null 2>&1; then
    echo "❌ WordPress installation not found."
    exit 1
fi

echo "✅ WordPress installation detected."
echo ""

###############################################################################
# WordPress Version
###############################################################################

echo "-------------------------------------------------------"
echo "WordPress"
echo "-------------------------------------------------------"

echo "Version : $(wp core version)"

echo ""

###############################################################################
# PHP Information
###############################################################################

echo "-------------------------------------------------------"
echo "PHP"
echo "-------------------------------------------------------"

echo "Version : $(php -r 'echo PHP_VERSION;')"

echo ""

###############################################################################
# MySQL Version
###############################################################################

echo "-------------------------------------------------------"
echo "Database"
echo "-------------------------------------------------------"

echo "MySQL Version"

wp db query "SELECT VERSION();" --skip-column-names

echo ""

###############################################################################
# Site Information
###############################################################################

echo "-------------------------------------------------------"
echo "Site Information"
echo "-------------------------------------------------------"

echo "Site URL"

wp option get siteurl

echo ""

echo "Home URL"

wp option get home

echo ""

###############################################################################
# Active Theme
###############################################################################

echo "-------------------------------------------------------"
echo "Theme"
echo "-------------------------------------------------------"

wp theme list

echo ""

###############################################################################
# Active Plugins
###############################################################################

echo "-------------------------------------------------------"
echo "Plugins"
echo "-------------------------------------------------------"

wp plugin list

echo ""

###############################################################################
# Plugin Updates
###############################################################################

echo "-------------------------------------------------------"
echo "Plugin Updates"
echo "-------------------------------------------------------"

UPDATES=$(wp plugin list --update=available --field=name)

if [ -z "$UPDATES" ]; then

    echo "✅ All plugins are up to date."

else

    echo "⚠ Available Updates"

    echo "$UPDATES"

fi

echo ""

###############################################################################
# Theme Updates
###############################################################################

echo "-------------------------------------------------------"
echo "Theme Updates"
echo "-------------------------------------------------------"

THEME_UPDATES=$(wp theme list --update=available --field=name)

if [ -z "$THEME_UPDATES" ]; then

    echo "✅ All themes are up to date."

else

    echo "⚠ Available Updates"

    echo "$THEME_UPDATES"

fi

echo ""

###############################################################################
# Database Status
###############################################################################

echo "-------------------------------------------------------"
echo "Database Check"
echo "-------------------------------------------------------"

wp db check

echo ""

###############################################################################
# Database Size
###############################################################################

echo "-------------------------------------------------------"
echo "Database Size"
echo "-------------------------------------------------------"

wp db size

echo ""

###############################################################################
# Debug Mode
###############################################################################

echo "-------------------------------------------------------"
echo "Debug Configuration"
echo "-------------------------------------------------------"

DEBUG=$(wp config get WP_DEBUG 2>/dev/null || echo "Not Defined")

echo "WP_DEBUG : $DEBUG"

echo ""

###############################################################################
# Cache
###############################################################################

echo "-------------------------------------------------------"
echo "Cache"
echo "-------------------------------------------------------"

echo "Flushing Object Cache..."

wp cache flush

echo "Done."

echo ""

###############################################################################
# Scheduled Events
###############################################################################

echo "-------------------------------------------------------"
echo "WP-Cron"
echo "-------------------------------------------------------"

wp cron event list

echo ""

###############################################################################
# Disk Usage
###############################################################################

echo "-------------------------------------------------------"
echo "Disk Usage"
echo "-------------------------------------------------------"

df -h .

echo ""

###############################################################################
# Server Load
###############################################################################

echo "-------------------------------------------------------"
echo "System Load"
echo "-------------------------------------------------------"

uptime

echo ""

###############################################################################
# Memory Usage
###############################################################################

echo "-------------------------------------------------------"
echo "Memory"
echo "-------------------------------------------------------"

free -m

echo ""

###############################################################################
# Final Report
###############################################################################

echo "======================================================="
echo "Health Check Completed"
echo "======================================================="

echo ""

echo "Summary"

echo "-------"

echo "✓ WordPress Installation Verified"

echo "✓ PHP Version Checked"

echo "✓ Database Verified"

echo "✓ Plugins Reviewed"

echo "✓ Themes Reviewed"

echo "✓ Cache Flushed"

echo "✓ WP-Cron Checked"

echo "✓ Disk Usage Reviewed"

echo "✓ System Resources Reviewed"

echo ""

echo "If any warnings appeared above, investigate them before"
echo "performing updates or deploying configuration changes."

echo ""

echo "Completed Successfully."
